/**
 * Put a content hash in the minified build file names
 * (`index.min.js` → `index.min.1a2b3c4d.js`) and record them in
 * `build/manifest.php`. A cache that ignores `?ver=` (Cloudflare's "Ignore
 * query string", page-cache plugins) then can't serve an old script after an
 * update, because every release has new file names.
 *
 * Exception: a file belonging to a webpack async chunk (anything loaded via
 * `import()`, not a `<script>` tag PHP enqueues by name) keeps its built
 * filename exactly as `AsyncChunkManifestPlugin` in webpack.config.js left
 * it — webpack's own runtime has that filename baked in at compile time, so
 * renaming it here would make every request for that chunk 404. Those
 * chunks already get cache-busting from `chunkFilename`'s own `?ver=` query.
 */
const crypto = require( 'crypto' );
const fs = require( 'fs' );
const path = require( 'path' );

const buildDir = path.resolve( __dirname, '..', '..', 'build' );
const hashed = /\.min\.[0-9a-f]{8}\.(js|css)$/;
const minified = /\.min\.(js|css)$/;

const asyncManifestFile = path.join( buildDir, '.async-chunk-files.json' );
let asyncFiles = new Set();
if ( fs.existsSync( asyncManifestFile ) ) {
	asyncFiles = new Set( JSON.parse( fs.readFileSync( asyncManifestFile, 'utf8' ) ) );
	fs.unlinkSync( asyncManifestFile );
}

function walk( dir ) {
	return fs.readdirSync( dir, { withFileTypes: true } ).flatMap( ( entry ) => {
		const full = path.join( dir, entry.name );
		return entry.isDirectory() ? walk( full ) : [ full ];
	} );
}

const files = walk( buildDir );
files.filter( ( f ) => hashed.test( f ) ).forEach( ( f ) => fs.unlinkSync( f ) );

const manifest = {};
for ( const file of files.filter( ( f ) => minified.test( f ) && ! hashed.test( f ) ) ) {
	const relative = path.relative( buildDir, file ).split( path.sep ).join( '/' );
	if ( asyncFiles.has( relative ) ) {
		continue;
	}
	const hash = crypto
		.createHash( 'md5' )
		.update( fs.readFileSync( file ) )
		.digest( 'hex' )
		.slice( 0, 8 );
	const target = file.replace( minified, `.min.${ hash }.$1` );
	fs.renameSync( file, target );
	manifest[ relative ] = hash;
}

const lines = Object.keys( manifest )
	.sort()
	.map( ( key ) => `\t'${ key }' => '${ manifest[ key ] }',` );
fs.writeFileSync(
	path.join( buildDir, 'manifest.php' ),
	`<?php\n// Generated by tools/build/hash-build-files.js — do not edit.\nreturn [\n${ lines.join( '\n' ) }\n];\n`
);
console.log( `hash-build-files: ${ lines.length } files` );
